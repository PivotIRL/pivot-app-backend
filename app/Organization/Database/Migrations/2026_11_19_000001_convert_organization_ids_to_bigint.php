<?php

use Illuminate\Database\Migrations\Migration;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;

/**
 * Converts organizations.id (and every organization_id foreign key) from UUID to auto-increment BIGINT.
 *
 * The earlier create_* migrations are left unchanged on purpose. A fresh install first builds the UUID schema and
 * this migration then converts it (on empty tables), so fresh and upgraded databases end with the same schema.
 *
 * Safety design:
 * - Runs in the migration transaction: any failed check rolls everything back.
 * - Every organization keeps a stable numeric ID recorded in `organization_id_map` (kept after the migration).
 * - Foreign keys, unique constraints and indexes (including partial ones) are discovered from the catalog and
 *   recreated from their exact definitions. Anything that would be lost silently (a table with organization_id but no
 *   foreign key, CHECK/EXCLUDE/primary-key constraints, defaults, generated columns, triggers, expression or predicate
 *   indexes) makes the migration abort instead.
 * - Audit rows (`target_id` and metadata references) are remapped.
 * - Idempotent: does nothing if organizations.id is already numeric.
 * - down() restores UUIDs from the map. Organizations created after the conversion get a new UUID, which is added
 *   to the map, so they are not lost (their numeric IDs are no longer valid after a rollback).
 */
return new class extends Migration
{
    private const MAP_TABLE = 'organization_id_map';

    /** Metadata keys allowed to hold an organization reference. A UUID anywhere else aborts the migration. */
    private const METADATA_KEYS = ['organization_id', 'previous_organization_id', 'from_organization_id', 'to_organization_id'];

    private const AUDIT_TABLE = 'organization_audit_logs';

    private const ORGANIZATION_TARGET_TYPES = ['organization', 'App\\Organization\\Models\\Organization'];

    public function up(): void
    {
        if ($this->requirePostgres() === false || $this->organizationIdType() !== 'uuid') {
            return;
        }

        // Lock first, then look: definitions and row counts are only meaningful once nobody can change them.
        $tables = $this->lockAndDiscoverTables();
        $this->assertChildTablesHaveColumn($tables);
        $definitions = $this->captureDefinitions($tables);
        $before = $this->countRows(['organizations', ...$tables]);

        $this->prepareMap();

        // 1. Add the numeric columns and backfill them from the map.
        DB::statement('ALTER TABLE organizations ADD COLUMN new_id bigint');
        DB::statement('UPDATE organizations o SET new_id = m.new_id FROM '.self::MAP_TABLE.' m WHERE m.old_uuid = o.id');

        foreach ($tables as $table) {
            DB::statement("ALTER TABLE {$table} ADD COLUMN new_organization_id bigint");
            DB::statement(
                "UPDATE {$table} t SET new_organization_id = m.new_id FROM ".self::MAP_TABLE.' m WHERE m.old_uuid = t.organization_id'
            );

            $unmapped = DB::scalar("SELECT COUNT(*) FROM {$table} WHERE organization_id IS NOT NULL AND new_organization_id IS NULL");
            $this->assert((int) $unmapped === 0, "{$table}: {$unmapped} rows reference an organization missing from the map.");
        }

        $this->assert(
            (int) DB::scalar('SELECT COUNT(*) FROM organizations WHERE new_id IS NULL') === 0,
            'Some organizations have no numeric ID.'
        );

        // 2. Swap the columns. Dropping organization_id also drops its FK, unique constraints and indexes
        //    (all saved above); dropping organizations.id drops the primary key.
        foreach ($tables as $table) {
            DB::statement("ALTER TABLE {$table} DROP COLUMN organization_id");
            DB::statement("ALTER TABLE {$table} RENAME COLUMN new_organization_id TO organization_id");
        }

        DB::statement('ALTER TABLE organizations DROP COLUMN id');
        DB::statement('ALTER TABLE organizations RENAME COLUMN new_id TO id');
        DB::statement('ALTER TABLE organizations ALTER COLUMN id SET NOT NULL');
        DB::statement('ALTER TABLE organizations ADD PRIMARY KEY (id)');
        DB::statement('ALTER TABLE organizations ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');

        // 3. Sequence: never reuse an ID, including IDs held by the map.
        $next = $this->nextIdentityValue();
        DB::statement("ALTER TABLE organizations ALTER COLUMN id RESTART WITH {$next}");

        // 4. Recreate nullability, unique constraints, indexes and foreign keys exactly as they were.
        $this->restoreDefinitions($definitions);

        // 5. Audit rows.
        $this->remapAuditTargets(toNumeric: true);
        $this->remapAuditMetadata(toNumeric: true);

        // 6. Verify.
        $this->assertCounts($before, ['organizations', ...$tables]);
        $this->assertDefinitionsRestored($definitions);
        $this->assert($this->organizationIdType() === 'bigint', 'organizations.id is not bigint after conversion.');
        $this->assertIdentitySequence($next);
    }

    public function down(): void
    {
        if ($this->requirePostgres() === false || $this->organizationIdType() === 'uuid') {
            return;
        }

        $this->assert(Schema::hasTable(self::MAP_TABLE), self::MAP_TABLE.' is missing; restore from the backup instead.');

        $tables = $this->lockAndDiscoverTables();
        $this->assertChildTablesHaveColumn($tables);
        $definitions = $this->captureDefinitions($tables);
        $before = $this->countRows(['organizations', ...$tables]);

        // Organizations created after the conversion have no UUID yet: give each one and record it in the map.
        $unmapped = DB::table('organizations')
            ->whereNotIn('id', DB::table(self::MAP_TABLE)->select('new_id'))
            ->pluck('id');

        foreach ($unmapped as $id) {
            DB::table(self::MAP_TABLE)->insert(['old_uuid' => (string) Str::uuid(), 'new_id' => $id]);
        }

        $this->remapAuditTargets(toNumeric: false);
        $this->remapAuditMetadata(toNumeric: false);

        DB::statement('ALTER TABLE organizations ADD COLUMN old_uuid uuid');
        DB::statement('UPDATE organizations o SET old_uuid = m.old_uuid FROM '.self::MAP_TABLE.' m WHERE m.new_id = o.id');

        foreach ($tables as $table) {
            DB::statement("ALTER TABLE {$table} ADD COLUMN old_organization_id uuid");
            DB::statement(
                "UPDATE {$table} t SET old_organization_id = m.old_uuid FROM ".self::MAP_TABLE.' m WHERE m.new_id = t.organization_id'
            );

            $missing = DB::scalar("SELECT COUNT(*) FROM {$table} WHERE organization_id IS NOT NULL AND old_organization_id IS NULL");
            $this->assert((int) $missing === 0, "{$table}: {$missing} rows could not be mapped back to a UUID.");
        }

        foreach ($tables as $table) {
            DB::statement("ALTER TABLE {$table} DROP COLUMN organization_id");
            DB::statement("ALTER TABLE {$table} RENAME COLUMN old_organization_id TO organization_id");
        }

        DB::statement('ALTER TABLE organizations DROP COLUMN id');
        DB::statement('ALTER TABLE organizations RENAME COLUMN old_uuid TO id');
        DB::statement('ALTER TABLE organizations ALTER COLUMN id SET NOT NULL');
        DB::statement('ALTER TABLE organizations ADD PRIMARY KEY (id)');

        $this->restoreDefinitions($definitions);

        $this->assertCounts($before, ['organizations', ...$tables]);
        $this->assertDefinitionsRestored($definitions);
        $this->assert($this->organizationIdType() === 'uuid', 'organizations.id is not uuid after rollback.');
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Catalog discovery
    // ---------------------------------------------------------------------------------------------------------------

    /**
     * Takes the locks before anything is read. Tables are discovered, locked, and discovered again: if a table was
     * added in between, the loop locks it too, so the list used for capture and conversion is the locked list.
     *
     * @return list<string> organizations' child tables, all locked.
     */
    private function lockAndDiscoverTables(): array
    {
        for ($attempt = 0; $attempt < 3; $attempt++) {
            $tables = $this->childTables();
            $this->lock(['organizations', ...$tables]);

            if ($this->childTables() === $tables) {
                return $tables;
            }
        }

        throw new RuntimeException('Organization ID conversion aborted: the set of tables referencing organizations keeps changing.');
    }

    private function requirePostgres(): bool
    {
        if (DB::getDriverName() !== 'pgsql') {
            throw new RuntimeException('This migration supports PostgreSQL only.');
        }

        return true;
    }

    private function organizationIdType(): ?string
    {
        return DB::scalar(
            "SELECT data_type FROM information_schema.columns
             WHERE table_schema = current_schema() AND table_name = 'organizations' AND column_name = 'id'"
        );
    }

    /** @return list<string> every table with a foreign key to organizations. */
    private function childTables(): array
    {
        $rows = DB::select(
            "SELECT DISTINCT c.conrelid::regclass::text AS tbl
             FROM pg_constraint c
             WHERE c.contype = 'f' AND c.confrelid = 'organizations'::regclass
             ORDER BY 1"
        );

        return array_map(fn ($row) => $row->tbl, $rows);
    }

    private function assertChildTablesHaveColumn(array $tables): void
    {
        $this->assert($tables !== [], 'No foreign keys to organizations were found.');
        $this->assertNoUnhandledOrganizationColumns($tables);
        $this->assertNoUnsupportedDependents($tables);

        foreach ($tables as $table) {
            $has = DB::scalar(
                "SELECT COUNT(*) FROM pg_attribute WHERE attrelid = ?::regclass AND attname = 'organization_id' AND NOT attisdropped",
                [$table]
            );
            $this->assert((int) $has === 1, "{$table} references organizations but has no organization_id column.");
        }

        // Every foreign key must be on organization_id; anything else needs a manual decision.
        $other = DB::select(
            "SELECT c.conrelid::regclass::text AS tbl, c.conname FROM pg_constraint c
             WHERE c.contype = 'f' AND c.confrelid = 'organizations'::regclass
             AND pg_get_constraintdef(c.oid) NOT LIKE 'FOREIGN KEY (organization_id) %'"
        );
        $this->assert($other === [], 'Unexpected foreign key to organizations: '.json_encode($other));
    }

    /**
     * A table that holds an organization reference but has no foreign key would be skipped by the discovery above
     * and silently stay UUID. Stop instead.
     */
    private function assertNoUnhandledOrganizationColumns(array $tables): void
    {
        $handled = array_map(
            fn (string $table) => trim(str_contains($table, '.') ? substr($table, strrpos($table, '.') + 1) : $table, '"'),
            $tables
        );

        $rows = DB::select(
            "SELECT c.table_name, c.column_name, c.data_type
             FROM information_schema.columns c
             JOIN information_schema.tables t
               ON t.table_schema = c.table_schema AND t.table_name = c.table_name AND t.table_type = 'BASE TABLE'
             WHERE c.table_schema = current_schema()
               AND c.column_name ~ '(^|_)(organization|org)_(id|uuid)\$'
             ORDER BY 1, 2"
        );
        // Only names that read as a reference to an organization count: organization_id, parent_organization_id,
        // org_uuid and the like. organization_count, organization_name or organizations_total are not references.

        $unhandled = [];
        foreach ($rows as $row) {
            $isMapColumn = $row->table_name === self::MAP_TABLE;
            $isHandled = $row->column_name === 'organization_id' && in_array($row->table_name, $handled, true);

            if (! $isMapColumn && ! $isHandled) {
                $unhandled[] = "{$row->table_name}.{$row->column_name} ({$row->data_type})";
            }
        }

        $this->assert($unhandled === [], 'Columns that reference organizations are not covered by a foreign key: '.implode(', ', $unhandled));
    }

    /**
     * Objects that DROP COLUMN would delete without a trace, or that cannot be recreated from a saved definition.
     * Refuse to convert until someone has decided how to carry them over.
     */
    private function assertNoUnsupportedDependents(array $tables): void
    {
        $in = implode(',', array_fill(0, count($tables), '?'));
        $problems = [];

        // CHECK, EXCLUDE and primary-key constraints that involve organization_id.
        foreach (DB::select(
            "SELECT DISTINCT c.conrelid::regclass::text AS tbl, c.conname, c.contype
             FROM pg_constraint c
             JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
             WHERE c.contype IN ('c', 'x', 'p') AND a.attname = 'organization_id' AND c.conrelid::regclass::text IN ({$in})",
            $tables
        ) as $row) {
            $kind = ['c' => 'CHECK', 'x' => 'EXCLUDE', 'p' => 'primary key'][$row->contype];
            $problems[] = "{$kind} constraint {$row->conname} on {$row->tbl}";
        }

        // Defaults, generated columns and identity on organization_id.
        foreach (DB::select(
            "SELECT a.attrelid::regclass::text AS tbl FROM pg_attribute a
             WHERE a.attname = 'organization_id' AND NOT a.attisdropped
               AND (a.atthasdef OR a.attgenerated <> '' OR a.attidentity <> '')
               AND a.attrelid::regclass::text IN ({$in})",
            $tables
        ) as $row) {
            $problems[] = "default, generated or identity definition on {$row->tbl}.organization_id";
        }

        // Triggers can read organization_id (or organizations.id) in their body; there is no reliable way to carry them over.
        foreach (DB::select(
            "SELECT t.tgrelid::regclass::text AS tbl, t.tgname FROM pg_trigger t
             WHERE NOT t.tgisinternal AND (t.tgrelid::regclass::text IN ({$in}) OR t.tgrelid = 'organizations'::regclass)",
            $tables
        ) as $row) {
            $problems[] = "trigger {$row->tgname} on {$row->tbl}";
        }

        // Constraints on organizations.id other than the primary key and the child foreign keys (those are handled).
        foreach (DB::select(
            "SELECT DISTINCT c.conname, c.contype FROM pg_constraint c
             JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
             WHERE c.conrelid = 'organizations'::regclass AND c.contype IN ('c', 'x', 'u') AND a.attname = 'id'"
        ) as $row) {
            $kind = ['c' => 'CHECK', 'x' => 'EXCLUDE', 'u' => 'unique'][$row->contype];
            $problems[] = "{$kind} constraint {$row->conname} on organizations.id";
        }

        // The primary key of organizations must be exactly (id). A composite key that includes id would be dropped
        // with the column and then replaced by a single-column key, silently changing what the table guarantees.
        foreach (DB::select(
            "SELECT c.conname, pg_get_constraintdef(c.oid) AS def FROM pg_constraint c
             WHERE c.conrelid = 'organizations'::regclass AND c.contype = 'p' AND cardinality(c.conkey) > 1
               AND EXISTS (SELECT 1 FROM pg_attribute a WHERE a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey) AND a.attname = 'id')"
        ) as $row) {
            $problems[] = "composite primary key {$row->conname} on organizations ({$row->def})";
        }

        // INCLUDE columns on the primary key's index. pg_constraint.conkey lists key columns only, so the check above
        // cannot see them: PRIMARY KEY (id) INCLUDE (name) looks like a plain single-column key. The key is dropped
        // with the id column and rebuilt as PRIMARY KEY (id), which would silently lose the INCLUDE columns.
        foreach (DB::select(
            "SELECT ic.relname AS name, pg_get_indexdef(i.indexrelid) AS def FROM pg_index i
             JOIN pg_class ic ON ic.oid = i.indexrelid
             WHERE i.indrelid = 'organizations'::regclass AND i.indisprimary AND i.indnatts > i.indnkeyatts"
        ) as $row) {
            $problems[] = "primary key index {$row->name} on organizations has INCLUDE columns that would be lost when it is rebuilt as PRIMARY KEY (id) ({$row->def})";
        }

        // Indexes on organizations other than the primary key that use id as a key or INCLUDE column, or mention it in
        // an expression or predicate. Dropping the id column would delete them, and they cannot be recreated as-is.
        foreach (DB::select(
            "SELECT ic.relname AS name FROM pg_index i
             JOIN pg_class ic ON ic.oid = i.indexrelid
             WHERE i.indrelid = 'organizations'::regclass AND NOT i.indisprimary
               AND (EXISTS (SELECT 1 FROM pg_attribute a WHERE a.attrelid = i.indrelid AND a.attnum = ANY (i.indkey) AND a.attname = 'id')
                    OR pg_get_indexdef(i.indexrelid) ~ '\\mid\\M')"
        ) as $row) {
            $problems[] = "index {$row->name} on organizations.id";
        }

        $this->assert($problems === [], 'Schema objects that would be lost in the conversion: '.implode('; ', $problems));
    }

    /**
     * Expression and partial-predicate indexes do not list organization_id as a key column, so the key-column capture
     * misses them and DROP COLUMN would delete them silently. Any index that mentions organization_id must be captured.
     */
    private function assertEveryIndexIsCaptured(array $tables, array $definitions): void
    {
        $in = implode(',', array_fill(0, count($tables), '?'));
        $captured = array_merge(
            array_map(fn ($item) => $item->name, $definitions['indexes']),
            array_map(fn ($item) => $item->name, $definitions['constraints']),
        );

        $missed = [];
        foreach (DB::select(
            "SELECT ic.relname AS name, i.indrelid::regclass::text AS tbl
             FROM pg_index i
             JOIN pg_class ic ON ic.oid = i.indexrelid
             WHERE NOT i.indisprimary AND i.indrelid::regclass::text IN ({$in})
               AND pg_get_indexdef(i.indexrelid) ~ '\\morganization_id\\M'",
            $tables
        ) as $row) {
            if (! in_array($row->name, $captured, true)) {
                $missed[] = "{$row->name} on {$row->tbl}";
            }
        }

        $this->assert($missed === [], 'Indexes that use organization_id outside their key columns cannot be carried over: '.implode(', ', $missed));
    }

    private function assertIdentitySequence(int $expectedNext): void
    {
        $column = DB::selectOne(
            "SELECT is_identity, identity_generation FROM information_schema.columns
             WHERE table_schema = current_schema() AND table_name = 'organizations' AND column_name = 'id'"
        );
        $this->assert(
            $column !== null && $column->is_identity === 'YES' && $column->identity_generation === 'BY DEFAULT',
            'organizations.id is not a BY DEFAULT identity column.'
        );

        $sequence = DB::scalar("SELECT pg_get_serial_sequence('organizations', 'id')");
        $this->assert(is_string($sequence) && $sequence !== '', 'organizations.id has no owned sequence.');

        // After RESTART WITH the sequence has not handed out a value yet: the next value is exactly last_value.
        $state = DB::selectOne("SELECT last_value, is_called FROM {$sequence}");
        $this->assert(
            (int) $state->last_value === $expectedNext && $state->is_called === false,
            "Identity sequence would not hand out {$expectedNext} next (last_value={$state->last_value}, is_called=".var_export($state->is_called, true).').'
        );

        $highest = max(
            (int) DB::scalar('SELECT COALESCE(MAX(id), 0) FROM organizations'),
            (int) DB::scalar('SELECT COALESCE(MAX(new_id), 0) FROM '.self::MAP_TABLE)
        );
        $this->assert($expectedNext > $highest, 'The next organization ID would collide with an existing or previously issued ID.');
    }

    /**
     * Exact definitions of everything that depends on organization_id, taken from the catalog.
     *
     * @return array{columns: array<string, bool>, constraints: list<object>, indexes: list<object>, foreign_keys: list<object>}
     */
    private function captureDefinitions(array $tables): array
    {
        $in = implode(',', array_fill(0, count($tables), '?'));

        $columns = [];
        foreach ($tables as $table) {
            $columns[$table] = (bool) DB::scalar(
                "SELECT attnotnull FROM pg_attribute WHERE attrelid = ?::regclass AND attname = 'organization_id' AND NOT attisdropped",
                [$table]
            );
        }

        $foreignKeys = DB::select(
            "SELECT c.conrelid::regclass::text AS tbl, c.conname AS name, pg_get_constraintdef(c.oid) AS def,
                    c.convalidated AS validated
             FROM pg_constraint c
             WHERE c.contype = 'f' AND c.confrelid = 'organizations'::regclass
             ORDER BY 1, 2"
        );

        $constraints = DB::select(
            "SELECT DISTINCT c.conrelid::regclass::text AS tbl, c.conname AS name, pg_get_constraintdef(c.oid) AS def,
                    c.convalidated AS validated
             FROM pg_constraint c
             JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
             WHERE c.contype = 'u' AND a.attname = 'organization_id' AND c.conrelid::regclass::text IN ({$in})
             ORDER BY 1, 2",
            $tables
        );

        $indexes = DB::select(
            "SELECT DISTINCT i.indrelid::regclass::text AS tbl, ic.relname AS name, pg_get_indexdef(i.indexrelid) AS def
             FROM pg_index i
             JOIN pg_class ic ON ic.oid = i.indexrelid
             JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY (i.indkey)
             WHERE a.attname = 'organization_id' AND NOT i.indisprimary
               AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid)
               AND i.indrelid::regclass::text IN ({$in})
             ORDER BY 1, 2",
            $tables
        );

        $definitions = compact('columns', 'constraints', 'indexes') + ['foreign_keys' => $foreignKeys];
        $this->assertEveryIndexIsCaptured($tables, $definitions);

        return $definitions;
    }

    private function restoreDefinitions(array $definitions): void
    {
        foreach ($definitions['columns'] as $table => $notNull) {
            if ($notNull) {
                DB::statement("ALTER TABLE {$table} ALTER COLUMN organization_id SET NOT NULL");
            }
        }

        foreach ($definitions['constraints'] as $constraint) {
            DB::statement("ALTER TABLE {$constraint->tbl} ADD CONSTRAINT \"{$constraint->name}\" {$this->definitionWithValidity($constraint)}");
        }

        foreach ($definitions['indexes'] as $index) {
            DB::statement($index->def);
        }

        // A validated foreign key is re-validated against every row, so an orphan fails the migration here. A foreign
        // key that was NOT VALID is recreated NOT VALID: the conversion neither hides nor "repairs" its orphans.
        foreach ($definitions['foreign_keys'] as $foreignKey) {
            DB::statement("ALTER TABLE {$foreignKey->tbl} ADD CONSTRAINT \"{$foreignKey->name}\" {$this->definitionWithValidity($foreignKey)}");
        }
    }

    /** pg_get_constraintdef() appends NOT VALID itself; make the captured validity explicit instead of implied. */
    private function definitionWithValidity(object $constraint): string
    {
        $definition = preg_replace('/\s+NOT VALID\s*$/i', '', $constraint->def);

        return $constraint->validated ? $definition : $definition.' NOT VALID';
    }

    private function assertDefinitionsRestored(array $definitions): void
    {
        foreach ($definitions['indexes'] as $index) {
            $exists = DB::scalar('SELECT COUNT(*) FROM pg_indexes WHERE indexname = ?', [$index->name]);
            $this->assert((int) $exists === 1, "Index {$index->name} was not restored.");
        }

        foreach ([...$definitions['constraints'], ...$definitions['foreign_keys']] as $constraint) {
            $valid = DB::scalar(
                'SELECT convalidated FROM pg_constraint WHERE conname = ? AND conrelid = ?::regclass',
                [$constraint->name, $constraint->tbl]
            );
            $this->assert($valid !== null, "Constraint {$constraint->name} on {$constraint->tbl} was not restored.");
            $this->assert(
                (bool) $valid === (bool) $constraint->validated,
                "Constraint {$constraint->name} on {$constraint->tbl} changed validity (was ".($constraint->validated ? 'validated' : 'NOT VALID').').'
            );
        }
    }

