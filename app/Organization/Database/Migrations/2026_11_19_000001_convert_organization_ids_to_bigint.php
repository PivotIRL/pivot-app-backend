    private function prepareMap(): void
    {
        // Kept after the migration: audit trail for the conversion and the basis for down().
        DB::statement(
            'CREATE TABLE IF NOT EXISTS '.self::MAP_TABLE.' (
                old_uuid uuid PRIMARY KEY,
                new_id bigint NOT NULL UNIQUE,
                created_at timestamp NOT NULL DEFAULT now()
            )'
        );

        // Existing mappings are kept (a previous up/down cycle), so IDs stay stable. New organizations are appended.
        DB::statement(
            'INSERT INTO '.self::MAP_TABLE.' (old_uuid, new_id)
             SELECT o.id, COALESCE((SELECT MAX(new_id) FROM '.self::MAP_TABLE.'), 0)
                          + ROW_NUMBER() OVER (ORDER BY o.created_at NULLS LAST, o.id)
             FROM organizations o
             WHERE NOT EXISTS (SELECT 1 FROM '.self::MAP_TABLE.' m WHERE m.old_uuid = o.id)'
        );

        $this->assert(
            (int) DB::scalar('SELECT COUNT(*) FROM organizations o WHERE NOT EXISTS (SELECT 1 FROM '.self::MAP_TABLE.' m WHERE m.old_uuid = o.id)') === 0,
            'The ID map does not cover every organization.'
        );
    }

    private function nextIdentityValue(): int
    {
        $max = max(
            (int) DB::scalar('SELECT COALESCE(MAX(id), 0) FROM organizations'),
            (int) DB::scalar('SELECT COALESCE(MAX(new_id), 0) FROM '.self::MAP_TABLE)
        );

        return $max + 1;
    }

