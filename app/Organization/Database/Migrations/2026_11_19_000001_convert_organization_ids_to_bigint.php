    private function remapAuditTargets(bool $toNumeric): void
    {
        if (! Schema::hasTable(self::AUDIT_TABLE)) {
            return;
        }

        $types = "'".implode("','", array_map(fn ($t) => str_replace("'", "''", $t), self::ORGANIZATION_TARGET_TYPES))."'";

        if ($toNumeric) {
            DB::statement(
                'UPDATE '.self::AUDIT_TABLE." a SET target_id = m.new_id::text FROM ".self::MAP_TABLE." m
                 WHERE a.target_type IN ({$types}) AND lower(a.target_id) = m.old_uuid::text"
            );

            $left = DB::scalar(
                'SELECT COUNT(*) FROM '.self::AUDIT_TABLE." WHERE target_type IN ({$types}) AND target_id ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'"
            );
            $this->assert((int) $left === 0, "{$left} audit rows still hold an organization UUID in target_id.");

            return;
        }

        DB::statement(
            'UPDATE '.self::AUDIT_TABLE." a SET target_id = m.old_uuid::text FROM ".self::MAP_TABLE." m
             WHERE a.target_type IN ({$types}) AND a.target_id = m.new_id::text"
        );
    }

    private function remapAuditMetadata(bool $toNumeric): void
    {
        if (! Schema::hasTable(self::AUDIT_TABLE)) {
            return;
        }

        $lookup = $toNumeric
            ? DB::table(self::MAP_TABLE)->pluck('new_id', 'old_uuid')->mapWithKeys(fn ($id, $uuid) => [strtolower($uuid) => (int) $id])->all()
            : DB::table(self::MAP_TABLE)->pluck('old_uuid', 'new_id')->all();

        if ($lookup === []) {
            return;
        }

        $query = DB::table(self::AUDIT_TABLE)->whereNotNull('metadata');

        $toNumeric
            ? $query->whereRaw('EXISTS (SELECT 1 FROM '.self::MAP_TABLE.' m WHERE position(m.old_uuid::text in lower('.self::AUDIT_TABLE.'.metadata::text)) > 0)')
            : $query->whereRaw(self::AUDIT_TABLE.".metadata::text ~ '\"(".implode('|', self::METADATA_KEYS).")\"'");

        $unexpected = [];

        $query->select('id', 'metadata')->orderBy('id')->chunkById(500, function ($rows) use ($lookup, $toNumeric, &$unexpected): void {
            foreach ($rows as $row) {
                $decoded = json_decode($row->metadata, true);
                if (! is_array($decoded)) {
                    continue;
                }

                $rewritten = $this->rewriteReferences($decoded, $lookup, $toNumeric);

                if ($toNumeric && $this->containsAny(json_encode($rewritten), array_keys($lookup))) {
                    $unexpected[] = $row->id;

                    continue;
                }

                DB::table(self::AUDIT_TABLE)->where('id', $row->id)->update(['metadata' => json_encode($rewritten)]);
            }
        });

        // Better to stop than to rewrite JSON in places nobody has reviewed.
        $this->assert(
            $unexpected === [],
            'Organization UUIDs found in unexpected audit metadata keys (audit log ids: '.implode(', ', array_slice($unexpected, 0, 20)).'). Nothing was changed.'
        );
    }

    private function rewriteReferences(array $data, array $lookup, bool $toNumeric): array
    {
        foreach ($data as $key => $value) {
            if (is_array($value)) {
                $data[$key] = $this->rewriteReferences($value, $lookup, $toNumeric);
            } elseif (is_string($key) && in_array($key, self::METADATA_KEYS, true)) {
                if ($toNumeric) {
                    if (is_string($value) && isset($lookup[strtolower($value)])) {
                        $data[$key] = $lookup[strtolower($value)];
                    }

                    continue;
                }

                // Rolling back: the reference may be a JSON integer or a numeric string ("12"). Only these four
                // allowlisted keys are touched, so unrelated numbers that happen to equal an ID stay as they are.
                $numeric = match (true) {
                    is_int($value) => $value,
                    is_string($value) && ctype_digit($value) => (int) $value,
                    default => null,
                };

                if ($numeric !== null && isset($lookup[$numeric])) {
                    $data[$key] = $lookup[$numeric];
                }
            }
        }

        return $data;
    }

    private function containsAny(string $haystack, array $needles): bool
    {
        $haystack = strtolower($haystack);

        foreach ($needles as $needle) {
            if (str_contains($haystack, strtolower((string) $needle))) {
                return true;
            }
        }

        return false;
    }

    // ---------------------------------------------------------------------------------------------------------------
    // Helpers
    // ---------------------------------------------------------------------------------------------------------------

    /** The ID map is locked too when it exists (a previous up/down cycle, or the down direction). */
    private function lock(array $tables): void
    {
        if (Schema::hasTable(self::MAP_TABLE)) {
            $tables[] = self::MAP_TABLE;
        }

        DB::statement('LOCK TABLE '.implode(', ', $tables).' IN ACCESS EXCLUSIVE MODE');
    }

    /** @return array<string, int> */
    private function countRows(array $tables): array
    {
        $counts = [];
        foreach ($tables as $table) {
            $counts[$table] = (int) DB::scalar("SELECT COUNT(*) FROM {$table}");
        }

        return $counts;
    }

    private function assertCounts(array $before, array $tables): void
    {
        foreach ($this->countRows($tables) as $table => $count) {
            $this->assert($count === $before[$table], "{$table}: row count changed from {$before[$table]} to {$count}.");
        }
    }

    private function assert(bool $condition, string $message): void
    {
        if (! $condition) {
            throw new RuntimeException('Organization ID conversion aborted: '.$message);
        }
    }
